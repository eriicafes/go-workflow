package workflow

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"time"

	"github.com/eriicafes/go-workflow/internal"
	"github.com/eriicafes/go-workflow/workflowops"
)

// HookOption configures a hook token. Omit Token to generate one. MinRetention
// keeps a completed hook claimed until that duration has elapsed. Force moves a
// currently claimed token to the new hook.
type HookOption struct {
	Token        string
	MinRetention time.Duration
	Force        bool
}

// Hook receives one typed payload from ResumeHook. Creating it does not
// claim its token. Value or GetConflict claims the token from a workflow replay.
type Hook[T any] struct {
	token        string
	minRetention time.Duration
	force        bool
	task         *workflowops.Task
}

// NewHook creates a hook definition. The optional last option wins. An omitted
// token is derived from the run and replay position when Value or GetConflict
// first registers it, making hooks constructed in workflow bodies replay-safe.
func NewHook[T any](options ...HookOption) *Hook[T] {
	option := HookOption{}
	if len(options) != 0 {
		option = options[len(options)-1]
	}
	return &Hook[T]{
		token:        option.Token,
		minRetention: option.MinRetention,
		force:        option.Force,
	}
}

// Token returns the hook's stable token.
func (hook *Hook[T]) Token() string {
	return hook.token
}

// Task returns the registered hook operation. It returns ErrHookNotRegistered
// until Value, Wait, or GetConflict has registered the hook in a workflow replay.
func (hook *Hook[T]) Task() (*workflowops.Task, error) {
	if hook.task == nil {
		return nil, ErrHookNotRegistered
	}
	task := *hook.task
	return &task, nil
}

// Wait registers the hook when first reached, then waits for its payload.
func (hook *Hook[T]) Wait(ctx context.Context) error {
	_, err := hook.Value(ctx)
	return err
}

// Value registers the hook when first reached, suspends the workflow, and
// returns the typed payload supplied by ResumeHook.
func (hook *Hook[T]) Value(ctx context.Context) (T, error) {
	return hook.value(ctx, nil)
}

func (hook *Hook[T]) value(ctx context.Context, webhook *workflowops.Webhook) (T, error) {
	var zero T
	execution, active := workflowExecutionFromContext(ctx)
	if !active {
		return zero, ErrNoWorkflow
	}
	op, record, err := hook.register(ctx, execution, webhook)
	if err != nil {
		return zero, err
	}
	if record.Conflict != nil {
		return zero, ErrHookConflict
	}
	if op.Status == workflowops.StatusCompleted || op.Status == workflowops.StatusFailed || op.Status == workflowops.StatusCancelled {
		value, err := waitingOperationResult[T](execution.World(), execution.RunID(), op.Sequence).Value(ctx)
		return value, err
	}
	if err := execution.World().SuspendRun(ctx, execution.Lease()); err != nil {
		return zero, err
	}
	panic(internal.ErrReplaySuspended)
}

// GetConflict registers a hook and reports the owning run ID when another run
// already owns its token. It does not wait for a payload.
func (hook *Hook[T]) GetConflict(ctx context.Context) (string, bool, error) {
	return hook.getConflict(ctx, nil)
}

func (hook *Hook[T]) getConflict(ctx context.Context, webhook *workflowops.Webhook) (string, bool, error) {
	execution, active := workflowExecutionFromContext(ctx)
	if !active {
		return "", false, ErrNoWorkflow
	}
	_, record, err := hook.register(ctx, execution, webhook)
	if err != nil {
		return "", false, err
	}
	if record.Conflict == nil {
		return "", false, nil
	}
	return record.Conflict.RunID, true, nil
}

func (hook *Hook[T]) register(
	ctx context.Context,
	execution *workflowops.Execution,
	webhook *workflowops.Webhook,
) (workflowops.Operation, workflowops.Hook, error) {
	sequence := execution.Sequence()
	if hook.token == "" {
		// The run id is generated by the world; combining it with the durable
		// sequence makes this token stable across replay without persisting a
		// random value in the workflow body.
		hook.token = fmt.Sprintf("hook_%s_%d", execution.RunID(), sequence)
	}
	input, err := json.Marshal(struct {
		Option  HookOption           `json:"option"`
		Webhook *workflowops.Webhook `json:"webhook,omitempty"`
	}{
		Option: HookOption{
			Token:        hook.token,
			MinRetention: hook.minRetention,
			Force:        hook.force,
		},
		Webhook: webhook,
	})
	if err != nil {
		return workflowops.Operation{}, workflowops.Hook{}, err
	}
	op, err := execution.World().EnsureOperation(ctx, execution.Lease(), workflowops.OperationRequest{
		RunID:       execution.RunID(),
		Sequence:    sequence,
		Kind:        workflowops.KindHook,
		Identity:    "hook",
		Fingerprint: fingerprint("hook", 3),
		Input:       input,
	})
	if err != nil {
		return workflowops.Operation{}, workflowops.Hook{}, err
	}
	hook.task = &workflowops.Task{RunID: execution.RunID(), Sequence: sequence}
	if op.Status == workflowops.StatusCompleted || op.Status == workflowops.StatusFailed || op.Status == workflowops.StatusCancelled {
		return op, workflowops.Hook{}, nil
	}
	record, err := execution.World().RegisterHook(ctx, execution.Lease(), workflowops.HookRequest{
		Token:        hook.token,
		Task:         workflowops.Task{RunID: execution.RunID(), Sequence: sequence},
		MinRetention: hook.minRetention,
		Force:        hook.force,
		Webhook:      webhook,
	})
	return op, record, err
}

// GetHook resolves a registered token for payload type T.
func GetHook[T any](ctx context.Context, token string) (*Hook[T], bool, error) {
	client, _, err := clientFromContext(ctx)
	if err != nil {
		return nil, false, err
	}
	_, found, err := client.GetHook(ctx, token)
	if err != nil || !found {
		return nil, found, err
	}
	return &Hook[T]{token: token}, true, nil
}

// ResumeHook delivers value to the currently registered hook token. It is valid
// in application handlers, steps, and workflow code with a client context.
func ResumeHook[T any](ctx context.Context, token string, value T) error {
	client, _, err := clientFromContext(ctx)
	if err != nil {
		return err
	}
	payload, err := json.Marshal(value)
	if err != nil {
		return fmt.Errorf("workflow: encode hook payload: %w", err)
	}
	return client.ResumeWebhook(ctx, token, payload)
}

// ResumeHookWithRetries retries a hook delivery while a newly started workflow is
// still reaching its registration point.
func ResumeHookWithRetries[T any](ctx context.Context, token string, value T, attempts int) error {
	if attempts <= 0 {
		return ErrHookNotFound
	}
	for attempt := range attempts {
		err := ResumeHook(ctx, token, value)
		if !errors.Is(err, ErrHookNotFound) {
			return err
		}
		timer := time.NewTimer(time.Duration(attempt+1) * 100 * time.Millisecond)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
	}
	return ErrHookNotFound
}
